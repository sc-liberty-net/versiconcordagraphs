"""Write OVERLAPS.md: where the concordagraph topics meet, for the future merge (Q6).

Two kinds of meeting point, both generated, never typed (Ethan, 16 Nov 2026):
  1. The same verse cited in more than one topic. Reference is identity
     (DESIGN.md decision 3), so these are the nodes a merge will fuse.
  2. Cross-topic connections: edges in any topic's corpus_edges.csv whose
     end carries another topic's prefix (sword:x4, tithe:kg2). build_graph.py
     holds these back from the single-topic page; the merge is where they land.

Run from this folder:  python overlaps.py
It reads the sibling topic folders named in TOPICS. A missing folder is an
error, not a skip: a register that silently drops a topic would be wrong."""
import csv, json, os, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
DESK = os.path.dirname(HERE)
TOPICS = [os.path.join(DESK, 'Biblography'),
          os.path.join(DESK, 'Swords & Words'),
          HERE]

mods = []
for d in TOPICS:
    for f in ('module.json', 'corpus_nodes.csv', 'corpus_edges.csv'):
        if not os.path.exists(os.path.join(d, f)):
            sys.exit(f'missing {f} in {d}')
    m = json.load(open(os.path.join(d, 'module.json'), encoding='utf-8'))
    nodes = list(csv.DictReader(open(os.path.join(d, 'corpus_nodes.csv'), encoding='utf-8')))
    edges = list(csv.DictReader(open(os.path.join(d, 'corpus_edges.csv'), encoding='utf-8')))
    mods.append((m['slug'], m['title'], nodes, edges))

title = {s: t for s, t, _, _ in mods}
refof = {}
byref = defaultdict(list)
for slug, _, nodes, _ in mods:
    for n in nodes:
        q = f"{slug}:{n['id']}"
        refof[q] = n['ref']
        byref[n['ref']].append((slug, n['id'], n['cluster'], n['gist']))

def q(slug, i):
    return i if ':' in i else f'{slug}:{i}'

L = ['# Overlaps between the concordagraph topics', '',
     'Generated by `overlaps.py`. Do not edit by hand; rerun it after any corpus change.', '',
     'Topics read: ' + ', '.join(f'{t} (`{s}`, {len(n)} passages)' for s, t, n, _ in mods) + '.', '',
     '## 1. The same verse in more than one topic', '',
     'Reference is identity: a merge fuses these into one node, and each topic keeps its own summary and group.', '']
shared = sorted((r, v) for r, v in byref.items() if len({s for s, *_ in v}) > 1)
if not shared:
    L.append('None.')
for r, v in shared:
    L.append(f'- **{r}**')
    for s, i, c, g in v:
        L.append(f'  - {title[s]} `{s}:{i}` [{c}]: {g}')
L += ['', '## 2. Connections that cross topics', '',
      'Written in one topic, pointing into another. Each keeps its kind and warrant tier.', '']
n = 0
bad = []
for slug, _, _, edges in mods:
    for e in edges:
        a, b = q(slug, e['source']), q(slug, e['target'])
        if a.split(':')[0] == b.split(':')[0]:
            continue
        for x in (a, b):
            if x not in refof:
                bad.append(f'{slug}: {a} -> {b}: no node {x}')
        n += 1
        L.append(f"- `{a}` ({refof.get(a, '?')}) → `{b}` ({refof.get(b, '?')}) · {e['kind']} · **{e['warrant']}**: {e['note']}")
if not n:
    L.append('None.')
L += ['', f'{len(shared)} shared verse(s); {n} cross-topic connection(s).', '']
if bad:
    sys.exit('cross-topic edge points at a missing node:\n  ' + '\n  '.join(bad))
open(os.path.join(HERE, 'OVERLAPS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
print(f'OVERLAPS.md: {len(shared)} shared verse(s), {n} cross-topic connection(s)')
